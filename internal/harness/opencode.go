// OpenCode has no hook config; it runs JS/TS plugins. Carya writes a small
// plugin that runs `carya hook opencode post-tool` after every tool call. That
// snapshots the checkout and, after an edit, appends peers' changes to the
// edited files to the tool output the model reads: OpenCode's before-hooks
// can only block, not add context, and after the edit the conflict check
// already includes the agent's own change. OpenCode has no session-start
// hook either, so the plugin marks a session's first tool call and that
// call's output also gets the one-line tools hint.
const EventOpenCodePostTool = "post-tool"

// openCodeMarker identifies a plugin file Carya wrote and may replace.
const openCodeMarker = "Generated by `carya setup opencode`."

type openCodeHookInput struct {
	Tool         string          `json:"tool"`
	Args         json.RawMessage `json:"args"`
	CWD          string          `json:"cwd"`
	SessionStart bool            `json:"sessionStart"`
}

// RunOpenCodeHook handles one call from Carya's OpenCode plugin.
func RunOpenCodeHook(event string, stdin io.Reader, stdout io.Writer, opts HookOptions) error {
	if event != EventOpenCodePostTool {
		return fmt.Errorf("unknown opencode hook event %q", event)
	}
	var in openCodeHookInput
	if err := json.NewDecoder(stdin).Decode(&in); err != nil && err != io.EOF {
		return fmt.Errorf("read hook input: %w", err)
	}
	s, done, err := begin(in.CWD, "opencode", opts)
	if err != nil || s == nil {
		return err
	}
	defer done()

	if _, err := s.Snapshot(); err != nil {
		log.Printf("carya hook: snapshot after %s: %v", in.Tool, err)
	}
	if in.SessionStart {
		if _, err := io.WriteString(stdout, toolsHint); err != nil {
			return err
		}
	}
	paths, err := openCodeEditPaths(in.Tool, in.Args)
	if err != nil || len(paths) == 0 {
		return err
	}
	report, err := editReport(s, absPaths(in.CWD, paths), opts.now(), "")
	if err != nil || report == "" {
		return err
	}
	_, err = io.WriteString(stdout, report)
	return err
}

// openCodeEditPaths covers both plugin APIs: 1.x passes filePath to edit and
// write and patchText to apply_patch; 2.x passes path, and patchText to patch.
func openCodeEditPaths(tool string, args json.RawMessage) ([]string, error) {
	switch tool {
	case "edit", "write", "patch", "apply_patch", "multiedit":
	default:
		return nil, nil
	}
	var a struct {
		FilePath  string `json:"filePath"`
		Path      string `json:"path"`
		PatchText string `json:"patchText"`
	}
	if len(args) > 0 {
		if err := json.Unmarshal(args, &a); err != nil {
			return nil, fmt.Errorf("read %s args: %w", tool, err)
		}
	}
	switch {
	case a.FilePath != "":
		return []string{a.FilePath}, nil
	case a.Path != "":
		return []string{a.Path}, nil
	default:
		return ApplyPatchPaths(a.PatchText), nil
	}
}

// OpenCodePluginPath returns where scope's plugin file goes.
func OpenCodePluginPath(scope, repoRoot string) (string, error) {
	switch scope {
	case ScopeLocal, ScopeProject:
		return filepath.Join(repoRoot, ".opencode", "plugins", "carya.ts"), nil
	case ScopeUser:
		dir := os.Getenv("XDG_CONFIG_HOME")
		if dir == "" {
			home, err := os.UserHomeDir()
			if err != nil {
				return "", err
			}
			dir = filepath.Join(home, ".config")
		}
		return filepath.Join(dir, "opencode", "plugins", "carya.ts"), nil
	default:
		return "", fmt.Errorf("unknown scope %q (want %s, %s or %s)", scope, ScopeLocal, ScopeProject, ScopeUser)
	}
}

// One file serves both OpenCode plugin APIs: 2.x reads the default export's
// id and setup, 1.x its server function. It has no dependencies.
var openCodePlugin = template.Must(template.New("plugin").Parse(`// {{.Marker}} Re-run it to update this file,
// or run ` + "`carya setup opencode --remove`" + ` to delete it.
//
// After every tool call this publishes the checkout's working state for other
// agents, and after an edit it adds their unfinished changes to the edited
// files to what the model reads. A session's first tool call also gets
// Carya's one-line hint about its commands.
import { execFile } from "node:child_process"

const CARYA = {{.Carya}}
const ARGS = {{.Args}}

function carya(payload: unknown, cwd: string): Promise<string> {
  return new Promise((resolve) => {
    const child = execFile(CARYA, ARGS, { cwd, timeout: 30_000 }, (_err, stdout) =>
      resolve(String(stdout ?? "").trim()),
    )
    child.stdin?.on("error", () => {})
    child.stdin?.end(JSON.stringify(payload))
  })
}

// Sessions that have had the hint, by session ID ("" if the API gives none).
const hinted = new Set<string>()

// afterTool runs Carya for one finished tool call; add puts a note in front
// of the model and reports whether it could. A session keeps asking for the
// hint until one reaches the model.
async function afterTool(tool: unknown, args: unknown, session: unknown, cwd: string, add: (note: string) => boolean) {
  const id = String(session ?? "")
  const sessionStart = !hinted.has(id)
  if (sessionStart) hinted.add(id)
  const note = await carya({ tool, args, cwd, sessionStart }, cwd)
  if (!(note && add(note)) && sessionStart) hinted.delete(id)
}

export default {
  id: "carya",

  // OpenCode 2.x
  async setup(ctx: any) {
    const cwd = ctx.location?.directory ?? process.cwd()
    await ctx.tool.hook("execute.after", (e: any) =>
      afterTool(e.tool, e.input, e.sessionID, cwd, (note) => {
        if (e.status !== "completed" || !e.result) return false
        const content = e.result.content
        if (typeof content === "string") e.result = { ...e.result, content: content + "\n\n" + note }
        else if (Array.isArray(content)) e.result = { ...e.result, content: [...content, { type: "text", text: note }] }
        else return false
        return true
      }),
    )
  },

  // OpenCode 1.x
  async server(input: any) {
    const cwd = input?.directory ?? process.cwd()
    return {
      "tool.execute.after": (i: any, o: any) =>
        afterTool(i.tool, i.args, i.sessionID, cwd, (note) => {
          o.output = (o.output ?? "") + "\n\n" + note
          return true
        }),
    }
  },
}
`))

func renderOpenCodePlugin(carya string, requireOptIn bool) ([]byte, error) {
	args := []string{"hook", "opencode", EventOpenCodePostTool}
	if requireOptIn {
		args = append(args, "--require-opt-in")
	}
	caryaJS, err := json.Marshal(carya)
	if err != nil {
		return nil, err
	}
	argsJS, err := json.Marshal(args)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	err = openCodePlugin.Execute(&b, map[string]string{
		"Marker": openCodeMarker,
		"Carya":  string(caryaJS),
		"Args":   string(argsJS),
	})
	return b.Bytes(), err
}

// InstallOpenCodePlugin writes Carya's OpenCode plugin to path. It replaces
// a plugin Carya wrote before but refuses to overwrite anyone else's file.
func InstallOpenCodePlugin(path, carya string, requireOptIn bool) (bool, error) {
	content, err := renderOpenCodePlugin(carya, requireOptIn)
	if err != nil {
		return false, err
	}
	existing, err := os.ReadFile(path)
	switch {
	case err == nil && bytes.Equal(existing, content):
		return false, nil
	case err == nil && !strings.Contains(string(existing), openCodeMarker):
		return false, fmt.Errorf("%s exists and was not written by carya; move it aside first", path)
	case err != nil && !os.IsNotExist(err):
		return false, err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return false, err
	}
	if err := os.WriteFile(path, content, 0644); err != nil {
		return false, err
	}
	return true, nil
}

// RemoveOpenCodePlugin deletes Carya's plugin at path, if it is Carya's.
func RemoveOpenCodePlugin(path string) (bool, error) {
	existing, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	if !strings.Contains(string(existing), openCodeMarker) {
		return false, fmt.Errorf("%s was not written by carya; leaving it", path)
	}
	return true, os.Remove(path)
}
